"""Generate the plate library: real plate solids from published dimensions.

These are **generic** plates. No manufacturer CAD is used, referenced or
implied, and every catalogue entry says so. What they are is dimensionally
faithful to the published classes they are drawn from — thickness, width,
hole pitch, screw seat, notch — with the construction real plates use:

* a bar with straight parallel edges and rounded ends, not a chain of washers;
* small circular notches in both edges between holes, where the plate is meant
  to bend (miniplates: notches so deep the plate is eyelets on thin bars);
* conical screw seats, and on locking plates a conical thread in the seat,
  drawn as rings at the thread pitch rather than a helix;
* a rounded edge break on the outline;
* preformed plates curved the way they sit on the jaw: body curvature through
  the plate's thickness, the gonial angle turn in the plate's own plane.

The faces are meshed with a fine constrained Delaunay triangulation so that no
edge along the plate exceeds about a millimetre. A coarse face mesh has long
triangles spanning several holes, and when such a plate is bent each triangle
stays flat: a chord across a curved plate.

This is a build tool and may use VTK; it makes no network calls.

    python3 tools/make_plate_assets.py

Writes binary PLY meshes and ``plates.json`` into ``mandiplan/data/plates``.
"""

