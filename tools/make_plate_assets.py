# -- meshing ----------------------------------------------------------------


def _face(outer: np.ndarray, holes: list[np.ndarray], z: float):
    """Constrained Delaunay of one face, with a fine interior point grid."""
    lo, hi = outer.min(axis=0), outer.max(axis=0)
    gx_step, gy_step = FACE_GRID_MM
    xs = np.arange(lo[0] + gx_step / 2, hi[0], gx_step)
    ys = np.arange(lo[1] + gy_step / 2, hi[1], gy_step)
    gx, gy = np.meshgrid(xs, ys)
    gx = gx + (np.arange(len(ys))[:, None] % 2) * gx_step / 2
    candidates = np.column_stack([gx.ravel(), gy.ravel()])
    margin = 0.22
    keep = point_in_polygon(candidates, outer)
    d_edge = np.min(np.linalg.norm(candidates[:, None] - outer[None], axis=2), axis=1)
    keep &= d_edge > margin
    for loop in holes:
        centre = loop.mean(axis=0)
        radius = float(np.linalg.norm(loop[0] - centre))
        keep &= np.linalg.norm(candidates - centre, axis=1) > radius + margin
    points2 = np.vstack([outer, *holes, candidates[keep]])

    vtk_points = vtk.vtkPoints()
    vtk_points.SetData(
        numpy_to_vtk(np.column_stack([points2, np.zeros(len(points2))]), deep=True)
    )
    constraints = vtk.vtkPolyData()
    constraints.SetPoints(vtk_points)
    polys = vtk.vtkCellArray()
    polys.InsertNextCell(len(outer))
    for i in range(len(outer)):  # counter-clockwise: keep the inside
        polys.InsertCellPoint(i)
    start = len(outer)
    for loop in holes:  # clockwise: cut out
        polys.InsertNextCell(len(loop))
        for i in reversed(range(start, start + len(loop))):
            polys.InsertCellPoint(i)
        start += len(loop)
    constraints.SetPolys(polys)

    cloud = vtk.vtkPolyData()
    cloud.SetPoints(vtk_points)
    delaunay = vtk.vtkDelaunay2D()
    delaunay.SetInputData(cloud)
    delaunay.SetSourceData(constraints)
    delaunay.SetTolerance(1e-9)
    delaunay.Update()
    out = delaunay.GetOutput()
    if out.GetNumberOfPoints() != len(points2):
        raise RuntimeError("Delaunay merged input points; face would not close")
    triangles = vtk_to_numpy(out.GetPolys().GetConnectivityArray()).reshape(-1, 3)
    return np.column_stack([points2, np.full(len(points2), z)]), triangles


def _ring_strip(ring_count: int, per_ring: int, base: int) -> list[tuple[int, int, int]]:
    tris = []
    for j in range(ring_count - 1):
        a, b = base + j * per_ring, base + (j + 1) * per_ring
        for k in range(per_ring):
            k2 = (k + 1) % per_ring
            tris.append((a + k, a + k2, b + k2))
            tris.append((a + k, b + k2, b + k))
    return tris


def flat_solid(shape: PlateShape) -> tuple[np.ndarray, np.ndarray]:
    """The unbent plate as a watertight, outward-oriented triangle mesh."""
    t = shape.thickness_mm
    top, bottom = t / 2.0, -t / 2.0
    r = shape.edge_radius_mm
    rings: list[tuple[float, float]] = []
    for phi in np.linspace(0.0, math.pi / 2.0, 4):
        rings.append((r - r * math.sin(phi), top - r + r * math.cos(phi)))
    for phi in np.linspace(math.pi / 2.0, 0.0, 4):
        rings.append((r - r * math.sin(phi), bottom + r - r * math.cos(phi)))
    rings = [ring for i, ring in enumerate(rings) if i == 0 or ring != rings[i - 1]]

    pieces: list[np.ndarray] = []
    tris: list[tuple[int, int, int]] = []

    def add(points, triangles):
        base = sum(len(p) for p in pieces)
        pieces.append(points)
        tris.extend((a + base, b + base, c + base) for a, b, c in triangles)

    loops = [outline(shape, inset) for inset, _ in rings]
    wall = np.vstack([np.column_stack([loop, np.full(len(loop), z)])
                      for loop, (_, z) in zip(loops, rings)])
    add(wall, _ring_strip(len(rings), len(loops[0]), 0))

    section = shape.hole.section(t)
    for x in shape.hole_x_mm:
        stack = np.vstack([
            np.column_stack([hole_loop(x, radius, HOLE_SAMPLES), np.full(HOLE_SAMPLES, z)])
            for radius, z in section
        ])
        add(stack, _ring_strip(len(section), HOLE_SAMPLES, 0))

    add(*_face(loops[0], [hole_loop(x, section[0][0], HOLE_SAMPLES)
                          for x in shape.hole_x_mm], top))
    add(*_face(loops[-1], [hole_loop(x, section[-1][0], HOLE_SAMPLES)
                           for x in shape.hole_x_mm], bottom))

    points = np.vstack(pieces)
    triangles = np.array(tris, dtype=np.int64)
    # Weld the seams, where faces meet walls vertex for vertex.
    keys = np.round(points / 1e-7).astype(np.int64)
    _, first, inverse = np.unique(keys, axis=0, return_index=True, return_inverse=True)
    points, triangles = points[first], inverse.reshape(-1)[triangles]
    good = (
        (triangles[:, 0] != triangles[:, 1])
        & (triangles[:, 1] != triangles[:, 2])
        & (triangles[:, 0] != triangles[:, 2])
    )
    return _orient(points, triangles[good])


def _orient(points: np.ndarray, triangles: np.ndarray):
    """Consistent, outward winding, proved rather than assumed.

    vtkPolyDataNormals with ConsistencyOn left a thousand directed edges in
    conflict on these meshes, which made the signed volume depend on where the
    plate sat. orient_outward walks the face adjacency instead.
    """
    return points, orient_outward(points, triangles)


# -- preforming --------------------------------------------------------------


def _rotate(v, axis, angle):
    axis = axis / np.linalg.norm(axis)
    return (v * math.cos(angle) + np.cross(axis, v) * math.sin(angle)
            + axis * float(np.dot(axis, v)) * (1.0 - math.cos(angle)))


def preform_stations(hole_x, program):
    """Where each hole ends up on a preformed plate, and its face normal.

    Walks along the plate integrating the preform's curvature: an ``arch``
    segment curls the plate through its thickness toward the bone, a ``turn``
    segment turns it in its own plane.
    """
    xs = np.asarray(hole_x, dtype=float)
    n = len(xs)
    rates = []
    for kind, first, last, degrees in program:
        first %= n
        last %= n
        u0, u1 = xs[first], xs[last]
        rates.append((kind, u0, u1, math.radians(degrees) / max(u1 - u0, 1e-9)))

    step = 0.05
    position = np.zeros(3)
    tangent, width, up = np.array([1.0, 0, 0]), np.array([0, 1.0, 0]), np.array([0, 0, 1.0])
    stations, normals = [position.copy()], [up.copy()]
    u = xs[0]
    for target in xs[1:]:
        while u < target - 1e-12:
            du = min(step, target - u)
            mid = u + du / 2.0
            for kind, u0, u1, rate in rates:
                if u0 <= mid <= u1:
                    angle = rate * du
                    if kind == "arch":
                        # Curl toward the bone: the tangent swings toward -up.
                        tangent = _rotate(tangent, width, angle)
                        up = _rotate(up, width, angle)
                    else:
                        tangent = _rotate(tangent, up, angle)
                        width = _rotate(width, up, angle)
            position = position + tangent * du
            u += du
        stations.append(position.copy())
        normals.append(up.copy())
    return np.array(stations), np.array(normals)


# -- marking -----------------------------------------------------------------


def marking_anchors(shape: PlateShape, tokens, height_mm: float = 0.9):
    """Short tokens laid into the solid face runs beside the screw seats."""
    if not tokens:
        return []
    anchors = []
    slots = [s for s in marking_slots(shape, height_mm) if s[1] - s[0] >= 1.8]
    for token, (x0, x1, y) in zip(tokens, slots):
        anchors.append({
            "text": token,
            "origin": [x0 + 0.15, y, shape.thickness_mm / 2.0],
            "along": [1.0, 0.0, 0.0],
            "outward": [0.0, 0.0, 1.0],
            "height_mm": height_mm,
            "max_length_mm": round(x1 - x0 - 0.3, 4),
        })
    return anchors


# -- output --------------------------------------------------------------------


def write_ply(path: Path, points: np.ndarray, triangles: np.ndarray) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "ply\nformat binary_little_endian 1.0\n"
        "comment generic plate asset, units mm, generated by make_plate_assets.py\n"
        f"element vertex {len(points)}\n"
        "property float x\nproperty float y\nproperty float z\n"
        f"element face {len(triangles)}\n"
        "property list uchar int vertex_indices\nend_header\n"
    ).encode("ascii")
    faces = np.zeros(len(triangles), dtype=[("n", "u1"), ("i", "<i4", 3)])
    faces["n"] = 3
    faces["i"] = triangles
    with path.open("wb") as handle:
        handle.write(header)
        handle.write(points.astype("<f4").tobytes())
        handle.write(faces.tobytes())


def build(family: Family, suffix: str, hole_x):
    s = family.section
    xs = np.asarray(hole_x, dtype=float)
    gaps = np.diff(xs)
    # Any gap longer than the pitch is a bridge: the narrow bar runs the whole
    # way across it, so its notch opens nearly the full gap.
    overrides = tuple(
        (i, NotchSpec(s.notch.depth_mm, float(g - (s.pitch_mm - s.notch.opening_mm))))
        for i, g in enumerate(gaps)
        if g > s.pitch_mm + 1e-6
    )
    shape = PlateShape(
        hole_x_mm=tuple(hole_x),
        width_mm=s.width_mm,
        thickness_mm=s.thickness_mm,
        hole=s.hole,
        notch=s.notch,
        edge_radius_mm=s.edge_radius_mm,
        gap_notches=overrides,
    )
    shape.validate()
    points, triangles = flat_solid(shape)
    xs = np.asarray(shape.hole_x_mm)
    holes = np.column_stack([xs, np.zeros(len(xs)), np.zeros(len(xs))])
    axes = np.tile([0.0, 0.0, 1.0], (len(xs), 1))

    anchors = marking_anchors(shape, family.marking + (f"{len(xs)}H",) if family.marking else ())
    if family.preform:
        stations, normals = preform_stations(xs, family.preform)
        extra = []
        for anchor in anchors:
            o = np.asarray(anchor["origin"])
            extra.extend([o, o + np.array([0.5, 0, 0]), o + np.array([0, 0, 0.5])])
        extra = np.array(extra).reshape(-1, 3)
        bent = bend_to_path(
            np.vstack([points, extra]), triangles, holes, axes, stations, normals,
            protected_radius_mm=s.hole.seat_diameter_mm / 2.0 + 0.5,
            min_bend_radius_mm=0.0, max_bend_deg_per_node=180.0,
        )
        points = bent.points[: len(points)]
        moved = bent.points[len(bent.points) - len(extra):]
        for k, anchor in enumerate(anchors):
            o, a, n = moved[3 * k], moved[3 * k + 1], moved[3 * k + 2]
            anchor["origin"] = o.tolist()
            anchor["along"] = ((a - o) / np.linalg.norm(a - o)).tolist()
            anchor["outward"] = ((n - o) / np.linalg.norm(n - o)).tolist()
        holes, axes = bent.hole_centres, bent.hole_axes
    # Express the asset in its own frame at the middle hole: origin at that
    # hole's centre, +x along the plate, +z out of the outer face.
    mid = len(holes) // 2
    lo, hi = max(mid - 1, 0), min(mid + 1, len(holes) - 1)
    along = holes[hi] - holes[lo]
    face = axes[mid] / np.linalg.norm(axes[mid])
    along = along - np.dot(along, face) * face
    along /= np.linalg.norm(along)
    frame = np.vstack([along, np.cross(face, along), face])  # rows: new x, y, z
    origin = holes[mid].copy()

    def local(v, is_point=True):
        v = np.asarray(v, dtype=float)
        return ((v - origin) if is_point else v) @ frame.T

    points = local(points)
    holes = local(holes)
    axes = local(axes, is_point=False)
    for anchor in anchors:
        anchor["origin"] = local(anchor["origin"]).round(6).tolist()
        anchor["along"] = local(anchor["along"], False).round(9).tolist()
        anchor["outward"] = local(anchor["outward"], False).round(9).tolist()
    return shape, points, triangles, holes, axes, anchors


def entry(family: Family, suffix: str, shape, points, triangles, holes, axes, anchors, audit):
    s = family.section
    lo, hi = points.min(axis=0), points.max(axis=0)
    count = len(holes)
    return {
        "id": f"{family.family}-{suffix}",
        "name": f"{family.name}, {count} holes" + (" (bridged)" if "bridge" in suffix else ""),
        "family": family.family,
        "category": family.category,
        "exact": False,
        "generic": True,
        "status_label": "Generic parametric approximation",
        "notice": GENERIC_NOTICE,
        "mesh": f"{family.family}-{suffix}.ply",
        "mesh_format": "ply",
        "units": "mm",
        "unit_scale": 1.0,
        "coordinate_convention": (
            "+z out of the outer face at the middle hole, the plate running "
            "along +x there; origin at the middle hole's centre"
        ),
        "thickness_mm": s.thickness_mm,
        "width_mm": s.width_mm,
        "hole_count": count,
        "hole_pitch_mm": s.pitch_mm,
        "hole_diameter_mm": s.hole.bore_diameter_mm,
        "seat_diameter_mm": s.hole.seat_diameter_mm,
        "locking": s.hole.locking,
        "thread_pitch_mm": s.hole.thread_pitch_mm if s.hole.locking else None,
        "notch": {"depth_mm": s.notch.depth_mm, "opening_mm": s.notch.opening_mm},
        "edge_radius_mm": s.edge_radius_mm,
        "length_mm": round(shape.length_mm, 4),
        "extent_mm": round(float((hi - lo).max()), 4),
        "flat_hole_x_mm": [round(float(x), 6) for x in shape.hole_x_mm],
        "hole_centres_mm": np.round(holes, 6).tolist(),
        "hole_axes": np.round(axes, 9).tolist(),
        "centreline_mm": np.round(holes, 6).tolist(),
        "side": "universal",
        "mirrorable": True,
        "preform": [list(step) for step in family.preform],
        "material_id": family.material_id,
        "load_bearing": family.load_bearing,
        "dimension_sources": list(family.sources),
        "deformation": {
            "min_bend_radius_mm": family.min_bend_radius_mm,
            "max_bend_deg_per_node": (
                family.max_bend_deg_per_node
                if family.max_bend_deg_per_node is not None
                else working_bend_limit(s, s.pitch_mm, family.material_id)
            ),
            "protected_radius_mm": round(s.hole.seat_diameter_mm / 2.0 + 0.5, 4),
            "bendable": "at the notches between holes",
        },
        "marking": anchors,
        "code": f"{family.code}-{suffix.upper()}",
        "provenance": PROVENANCE,
        "licence": LICENCE,
        "audit": audit,
        "notes": family.notes,
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=OUT_DIR)
    parser.add_argument("--family", default=None)
    args = parser.parse_args(argv)
    args.out.mkdir(parents=True, exist_ok=True)

    entries, failures = [], []
    for family in FAMILIES:
        if args.family and family.family != args.family:
            continue
        for suffix, hole_x in family.layouts:
            shape, points, triangles, holes, axes, anchors = build(family, suffix, hole_x)
            mesh = Mesh(points, triangles)
            audit = {
                "watertight": bool(mesh.is_watertight()),
                "outward": bool(mesh.is_outward()),
                "genus": int(mesh.genus()),
                "triangles": int(len(triangles)),
                "points": int(len(points)),
                "volume_mm3": round(float(mesh.volume_mm3()), 4),
            }
            name = f"{family.family}-{suffix}"
            write_ply(args.out / f"{name}.ply", points, triangles)
            entries.append(entry(family, suffix, shape, points, triangles, holes, axes, anchors, audit))
            ok = audit["watertight"] and audit["outward"] and audit["genus"] == len(holes)
            if not ok:
                failures.append(name)
            print(f"  {'ok ' if ok else 'BAD'} {name:<36} {audit['triangles']:>6} tris  "
                  f"genus {audit['genus']:>2}/{len(holes):<2} {shape.length_mm:6.1f} mm")

    if not args.family:
        for stale in args.out.glob("generic-*.stl"):
            stale.unlink()
    catalogue = {
        "note": [
            "Generic plate assets generated in this repository from published",
            "dimensional classes; see each entry's dimension_sources.",
            GENERIC_NOTICE,
            "No manufacturer CAD, part number or trade dress is used or implied.",
            "To add a licensed exact asset, drop its mesh and an entry here; set",
            "exact to true only when provenance and licence genuinely support it.",
        ],
        "generated_by": "tools/make_plate_assets.py",
        "plates": entries,
    }
    (args.out / "plates.json").write_text(json.dumps(catalogue, indent=2) + "\n", encoding="utf-8")
    print(f"\n{len(entries)} assets -> {args.out}")
    if failures:
        print(f"FAILED: {failures}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
