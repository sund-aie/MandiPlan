@dataclass(frozen=True)
class Section:
    """The cross-section and hole of a plate class."""

    thickness_mm: float
    width_mm: float
    pitch_mm: float
    hole: HoleSpec
    notch: NotchSpec
    edge_radius_mm: float = 0.3


